"""Freeze 20 structured, synthetic WF2 V3.5 mechanism cases.

The cases bypass the LLM and isolate deterministic conflict detection and Top-3
recommendation.  Gold labels are explicit and are not generated by production code.
"""

from __future__ import annotations

import json
from copy import deepcopy
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "data/eval_datasets/wf2_mechanism_v35.jsonl"
NOW = "2026-06-30T09:00:00"
DAY = "2026-07-06"


def _spec(
    *,
    participants: list[str] | None = None,
    exact_time: str | None = "10:00",
    duration: int = 60,
    location: str = "Orion",
    start: str = DAY,
    end: str | None = None,
) -> dict[str, Any]:
    return {
        "operation": "CREATE",
        "title": "Synthetic mechanism review",
        "participants": participants or ["bob"],
        "duration_minutes": duration,
        "date_window": {"start": start, "end": end or start},
        "exact_time": exact_time,
        "location": location,
        "mode": "in_person",
        "hard_constraints": {
            "working_hours_only": True,
            "required_room": True,
        },
        "soft_preferences": {},
    }


def _event(
    *,
    participants: list[str],
    start: str,
    end: str,
    location: str,
    day: str = DAY,
    organizer: str | None = None,
) -> dict[str, Any]:
    data: dict[str, Any] = {
        "title": "Existing synthetic booking",
        "participants": participants,
        "date": day,
        "start": start,
        "end": end,
        "location": location,
    }
    if organizer:
        data["organizer"] = organizer
    return data


def _conflict_case(
    case_id: str,
    expected: list[str],
    spec: dict[str, Any],
    events: list[dict[str, Any]],
    note: str,
) -> dict[str, Any]:
    return {
        "case_id": case_id,
        "group": "conflict",
        "now": NOW,
        "actor": "alice",
        "spec": spec,
        "seed_events": events,
        "gold": {
            "expected_requested_conflicts": expected,
            "note": note,
        },
    }


def _top3_case(
    case_id: str,
    spec: dict[str, Any],
    events: list[dict[str, Any]],
    *,
    exact_slot_should_rank_first: bool = False,
    expect_warning: bool = False,
    expect_no_feasible: bool = False,
    note: str,
) -> dict[str, Any]:
    return {
        "case_id": case_id,
        "group": "top3",
        "now": NOW,
        "actor": "alice",
        "spec": spec,
        "seed_events": events,
        "gold": {
            "exact_slot_should_rank_first": exact_slot_should_rank_first,
            "expect_warning": expect_warning,
            "expect_no_feasible": expect_no_feasible,
            "note": note,
        },
    }


def build_rows() -> list[dict[str, Any]]:
    conflict = [
        _conflict_case(
            "wf2-mech-conflict-01",
            ["participant_conflict"],
            _spec(participants=["bob"]),
            [_event(participants=["bob"], start="10:00", end="11:00", location="Lyra")],
            "full participant overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-02",
            ["participant_conflict"],
            _spec(participants=["chen"], exact_time="10:30"),
            [_event(participants=["chen"], start="10:00", end="11:00", location="Lyra")],
            "partial participant overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-03",
            ["participant_conflict"],
            _spec(participants=["bob"]),
            [_event(participants=["alice"], start="10:00", end="11:00", location="Lyra")],
            "organiser-only overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-04",
            ["room_conflict"],
            _spec(participants=["bob"]),
            [_event(participants=["dana"], start="10:00", end="11:00", location="Orion")],
            "full room overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-05",
            ["room_conflict"],
            _spec(participants=["bob"], exact_time="10:30"),
            [_event(participants=["dana"], start="10:00", end="11:00", location="Orion")],
            "partial room overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-06",
            ["room_conflict"],
            _spec(participants=["bob"], location="Orion room"),
            [_event(participants=["dana"], start="10:00", end="11:00", location="Orion")],
            "canonical room alias overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-07",
            ["participant_conflict", "room_conflict"],
            _spec(participants=["bob"]),
            [_event(participants=["bob"], start="10:00", end="11:00", location="Orion")],
            "full participant and room overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-08",
            ["participant_conflict", "room_conflict"],
            _spec(participants=["chen"], exact_time="10:30"),
            [_event(participants=["chen"], start="10:00", end="11:00", location="Orion")],
            "partial participant and room overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-09",
            ["participant_conflict", "room_conflict"],
            _spec(participants=["bob", "chen"]),
            [_event(participants=["chen"], start="10:00", end="11:00", location="Orion")],
            "multi-participant and room overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-10",
            [],
            _spec(participants=["bob"], exact_time="11:00"),
            [_event(participants=["bob"], start="10:00", end="11:00", location="Orion")],
            "back-to-back meetings do not overlap",
        ),
        _conflict_case(
            "wf2-mech-conflict-11",
            [],
            _spec(participants=["bob"]),
            [
                _event(
                    participants=["bob"],
                    start="10:00",
                    end="11:00",
                    location="Orion",
                    day="2026-07-07",
                )
            ],
            "same resources on a different date",
        ),
        _conflict_case(
            "wf2-mech-conflict-12",
            [],
            _spec(participants=["bob"]),
            [_event(participants=["dana"], start="10:00", end="11:00", location="Lyra")],
            "same time with different participant and room",
        ),
    ]

    dense = [
        _event(
            participants=["dana"],
            start="09:00",
            end="16:00",
            location="Orion",
        )
    ]
    full = [
        _event(
            participants=["dana"],
            start="09:00",
            end="18:00",
            location="Orion",
        )
    ]
    top3 = [
        _top3_case(
            "wf2-mech-top3-01",
            _spec(exact_time="10:00"),
            [],
            exact_slot_should_rank_first=True,
            note="free exact slot on one day",
        ),
        _top3_case(
            "wf2-mech-top3-02",
            _spec(
                exact_time="10:00",
                start="2026-07-06",
                end="2026-07-08",
            ),
            [],
            exact_slot_should_rank_first=True,
            note="free exact time across a three-day window",
        ),
        _top3_case(
            "wf2-mech-top3-03",
            _spec(exact_time="10:00"),
            [_event(participants=["bob"], start="10:00", end="11:00", location="Lyra")],
            expect_warning=True,
            note="occupied exact participant slot with alternatives",
        ),
        _top3_case(
            "wf2-mech-top3-04",
            _spec(
                exact_time="10:00",
                start="2026-07-06",
                end="2026-07-08",
            ),
            [_event(participants=["dana"], start="10:00", end="11:00", location="Orion")],
            expect_warning=True,
            note="occupied exact room on the first day of a multi-day window",
        ),
        _top3_case(
            "wf2-mech-top3-05",
            _spec(exact_time=None),
            [],
            note="flexible single-day request",
        ),
        _top3_case(
            "wf2-mech-top3-06",
            _spec(exact_time=None, start="2026-07-06", end="2026-07-08"),
            [],
            note="flexible multi-day request",
        ),
        _top3_case(
            "wf2-mech-top3-07",
            _spec(exact_time=None),
            dense,
            note="dense calendar with two meaningfully diverse options",
        ),
        _top3_case(
            "wf2-mech-top3-08",
            _spec(exact_time=None),
            full,
            expect_no_feasible=True,
            note="no feasible room slot",
        ),
    ]
    rows = deepcopy(conflict + top3)
    if len(rows) != 20 or len({row["case_id"] for row in rows}) != 20:
        raise RuntimeError("WF2 mechanism suite must contain 20 unique cases")
    return rows


def write() -> None:
    if OUTPUT.exists():
        raise RuntimeError(f"refusing to overwrite frozen V3.5 mechanism data: {OUTPUT}")
    OUTPUT.write_text(
        "".join(
            json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n"
            for row in build_rows()
        ),
        encoding="utf-8",
    )


if __name__ == "__main__":
    write()

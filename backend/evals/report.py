"""Consolidated results report — reads data/eval_results/*.jsonl → markdown with CIs.

    python -m backend.evals.report            # print to stdout
    python -m backend.evals.report --write    # also write docs/results_tables.md

For every eval name, the LATEST run per (model, dataset) condition is reported (runs
supersede within a condition; the full history stays in the jsonl). Proportion metrics
get Wilson 95% CIs — interval width is the honest statement of sample size.
"""
import argparse
import json
from collections import defaultdict

from .results_store import load_all
from .stats import wilson_ci

NAMES = ("scheduling", "triage", "position", "summary", "m4", "receipts")


def _ci(p, n) -> str:
    if p is None or n in (None, 0):
        return "—"
    lo, hi = wilson_ci(round(p * n), n)
    return f"{p:.2f} [{lo:.2f},{hi:.2f}]"


def _latest_per_condition(name: str) -> dict[tuple, dict]:
    out: dict[tuple, dict] = {}
    for e in load_all(name):                       # file order = chronological
        cond = (e.get("model") or "?", (e.get("params") or {}).get("dataset", "-"))
        out[cond] = e
    return out


def _tier_table(tiers: dict, metric_keys: list[str]) -> list[str]:
    head = "| tier | n | " + " | ".join(k.replace("_", " ") for k in metric_keys) + " |"
    sep = "|" + "---|" * (len(metric_keys) + 2)
    rows = [head, sep]
    for tier, m in tiers.items():
        n = m.get("n", 0)
        cells = [_ci(m.get(k), n) if k in m else "—" for k in metric_keys]
        rows.append(f"| {tier} | {n} | " + " | ".join(cells) + " |")
    return rows


def render(name: str, entry: dict) -> list[str]:
    model, ds = entry.get("model") or "?", (entry.get("params") or {}).get("dataset", "-")
    lines = [f"### {name} · model={model} · dataset={ds} · {entry['at']}", ""]
    r = entry["result"]
    if name == "scheduling" and "scheduling" in r:
        keys = ["date_correct", "time_correct", "participants_correct",
                "missing_detected", "conflict_correct", "correct_abstain"]
        lines += _tier_table(r["scheduling"], keys)
    elif name == "triage" and "triage" in r:
        lines += _tier_table(r["triage"], ["recall", "exact", "correct_refusal",
                                           "coverage"])
    elif name == "position" and "position" in r:
        lines += ["| length | position | n | recall | coverage |", "|---|---|---|---|---|"]
        for length, cells in r["position"].items():
            for pos, m in cells.items():
                lines.append(f"| {length} | {pos} | {m['n']} | "
                             f"{_ci(m.get('recall'), m['n'])} | "
                             f"{_ci(m.get('coverage'), m['n'])} |")
    elif name == "m4" and "policies" in r:
        lines += [f"n={r['n']} · injected-error cases={r['n_wrong']} "
                  f"(rate {r['error_rate']})", "",
                  "| policy | approve | false-accept | errors caught | edits/case |",
                  "|---|---|---|---|---|"]
        for pol, m in r["policies"].items():
            lines.append(f"| {pol} | {_ci(m['approve_rate'], r['n'])} | "
                         f"{_ci(m['false_accept_rate'], r['n'])} | "
                         f"{_ci(m['errors_caught'], r['n_wrong'])} | "
                         f"{m['edits_per_case']} |")
    elif name == "summary" and "faithfulness" in r:
        f = r["faithfulness"]
        lines += [f"generator={r.get('generator', '?')} · judge={r.get('judge', '?')} · "
                  f"n={r['n']}",
                  "",
                  f"- coverage: {_ci(r.get('coverage'), r['n'])}",
                  f"- faithfulness: {f.get('mean_faithfulness')}",
                  f"- summaries with ≥1 unsupported claim: "
                  f"{_ci(f.get('unsupported_rate'), f.get('n'))}"]
    else:
        lines += ["```json", json.dumps(r, indent=1)[:2000], "```"]
    lines.append("")
    return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true",
                    help="also write docs/results_tables.md")
    args = ap.parse_args()

    out: list[str] = ["# Generated results tables (Wilson 95% CIs)", "",
                      "_Auto-generated by `python -m backend.evals.report` from "
                      "`data/eval_results/`. Regenerate after new runs._", ""]
    by_name: dict[str, dict] = defaultdict(dict)
    for name in NAMES:
        by_name[name] = _latest_per_condition(name)
    for name in NAMES:
        for cond in sorted(by_name[name]):
            out += render(name, by_name[name][cond])

    text = "\n".join(out)
    print(text)
    if args.write:
        with open("docs/results_tables.md", "w", encoding="utf-8") as f:
            f.write(text + "\n")
        print("\n→ docs/results_tables.md")


if __name__ == "__main__":  # pragma: no cover
    main()
